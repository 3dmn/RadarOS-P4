void i18n_set_lang(app_lang_t lang) {
    s_lang = (lang == LANG_PL) ? LANG_PL : LANG_EN;
}

app_lang_t i18n_get_lang(void) {
    return s_lang;
}

const char *T(i18n_str_id_t id) {
    if (id < 0 || id >= STR_COUNT) return "";
    const char *s = s_strings[s_lang][id];
    return s ? s : "";
}
